let currentCategory = "All";


/* =========================================================
   DISPLAY TABLE
   ========================================================= */

function displayCerts() {


    const table =
        document.getElementById("certTable");


    const search =
        document
            .getElementById("search")
            .value
            .toLowerCase();


    const sort =
        document
            .getElementById("sortSelect")
            .value;


    /* FILTER */

    let filteredCerts =
        certs.filter(cert => {


            const matchesCategory =

                currentCategory === "All" ||

                cert.category ===
                currentCategory;

			const matchesSearch =
				(cert.category + ' ' + cert.certification)
					.toLowerCase()
					.includes(search.toLowerCase());

            return (
                matchesCategory &&
                matchesSearch
            );

        });


    /* SORT */

    filteredCerts.sort((a, b) => {


        if (sort === "site") {

            return a.site
                .localeCompare(b.site);

        }


        if (sort === "year") {

            return b.year - a.year;

        }


        if (sort === "category") {

            return a.category
                .localeCompare(b.category);

        }

    });


    /* CLEAR TABLE */

    table.innerHTML = "";


    /* NO RESULTS */

    if (filteredCerts.length === 0) {

        document
            .getElementById("noResults")
            .style.display = "block";

        return;

    }


    document
        .getElementById("noResults")
        .style.display = "none";


    /* BUILD ROWS */

    filteredCerts.forEach(cert => {


        const row =
            document.createElement("tr");


        row.innerHTML = `

            <td>
			<img class="img-fluid" src="${cert.image}" alt="" width="100" height="100">
            </td>

            <td>
			  <A href="${cert.site}" TARGET="_blank">${cert.certification}</A>
            </td>

            <td>
                <span class="badge">${cert.category}</span>
            </td>

            <td>
                ${cert.year}
            </td>
        `;


        table.appendChild(row);

    });

}


