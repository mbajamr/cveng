/* =========================================================
   CATEGORY COUNTS
   ========================================================= */

function updateCounts() {


    const categories = [
        "All",
        "AWS",
        "AGILE",
        "AZURE",
        "ORACLE",
        "ITIL"
    ];


    categories.forEach(category => {


        let count;


        if (category === "All") {

            count = certs.length;

        } else {

            count =
                certs.filter(
                    cert =>
                        cert.category ===
                        category
                ).length;

        }


        document
            .getElementById(
                "count-" + category
            )
            .textContent =
            count + " certs";

    });

}


